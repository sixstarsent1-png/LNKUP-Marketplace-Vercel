<?php
/**
 * Builds includes/location/data/us-places.php from public-domain US Census files.
 *
 * Usage (CLI only):
 *   php scripts/build-us-places.php <2023_Gaz_place_national.txt> <sub-est2023.csv>
 *
 * Sources (US Census Bureau, public domain):
 * - https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer/2023_Gaz_place_national.zip
 * - https://www2.census.gov/programs-surveys/popest/datasets/2020-2023/cities/totals/sub-est2023.csv
 *
 * Output: array keyed by normalized city name => list of [state, display name, lat, lng, population],
 * sorted by population descending. Incorporated places with >= 1,000 people and census-designated
 * places with >= 10,000 are kept so small-town events validate without bloating the file.
 *
 * @package LNKup_Marketplace
 */

declare(strict_types=1);

if ( PHP_SAPI !== 'cli' ) {
	exit( 1 );
}

[ , $gaz_path, $pop_path ] = $argv + array( null, '', '' );
if ( ! is_readable( (string) $gaz_path ) || ! is_readable( (string) $pop_path ) ) {
	fwrite( STDERR, "Usage: php build-us-places.php <gazetteer.txt> <sub-est2023.csv>\n" );
	exit( 1 );
}

/** Same normalization as LNKup_Location_Service::normalize_key(). */
function lnkup_build_key( string $name ): string {
	$name = strtolower( trim( $name ) );
	$name = str_replace( array( '.', "'", '’' ), '', $name );
	$name = preg_replace( '/[\s\-\/]+/', ' ', $name );
	$name = preg_replace( '/^saint /', 'st ', (string) $name );
	$name = preg_replace( '/^sainte /', 'ste ', (string) $name );
	$name = preg_replace( '/^fort /', 'ft ', (string) $name );
	$name = preg_replace( '/^mount /', 'mt ', (string) $name );
	return trim( (string) $name );
}

/** Strip the legal/statistical suffix ("city", "CDP", "consolidated government (balance)"). */
function lnkup_build_clean_name( string $name ): array {
	$aliases = array();
	if ( preg_match( '/^(.*?)\s+(?:(?:consolidated|metropolitan|metro|unified) government\s*\(balance\)|urban county)$/i', $name, $m ) ) {
		$name      = trim( $m[1] );
		$parts     = preg_split( '/[\-\/]/', $name );
		$aliases[] = trim( (string) $parts[0] );
	}
	$name = preg_replace( '/\s+\(balance\)$/i', '', $name );
	$name = preg_replace( '/\s+(city and borough|municipality|zona urbana|comunidad|urban county|city|town|village|borough|CDP)$/i', '', (string) $name );
	$name = trim( (string) $name );
	if ( 0 === stripos( $name, 'Urban ' ) ) {
		$aliases[] = substr( $name, 6 );
	}
	return array( $name, array_values( array_unique( array_filter( $aliases ) ) ) );
}

$population = array();
$pop_handle = fopen( (string) $pop_path, 'r' );
$header     = fgetcsv( $pop_handle );
$col        = array_flip( (array) $header );
while ( ( $row = fgetcsv( $pop_handle ) ) !== false ) {
	if ( '162' !== $row[ $col['SUMLEV'] ] ) {
		continue;
	}
	$geoid                = $row[ $col['STATE'] ] . $row[ $col['PLACE'] ];
	$population[ $geoid ] = (int) $row[ $col['POPESTIMATE2023'] ];
}
fclose( $pop_handle );

$places     = array();
$gaz_handle = fopen( (string) $gaz_path, 'r' );
$header     = array_map( 'trim', (array) fgetcsv( $gaz_handle, 0, "\t" ) );
$col        = array_flip( $header );
$kept       = 0;
while ( ( $row = fgetcsv( $gaz_handle, 0, "\t" ) ) !== false ) {
	$row      = array_map( 'trim', $row );
	$state    = $row[ $col['USPS'] ];
	$geoid    = $row[ $col['GEOID'] ];
	$raw_name = $row[ $col['NAME'] ];
	$is_cdp   = (bool) preg_match( '/\sCDP$/', $raw_name );
	$pop      = $population[ $geoid ] ?? 0;
	if ( $is_cdp ? $pop < 10000 : $pop < 1000 ) {
		continue;
	}
	list( $name, $aliases ) = lnkup_build_clean_name( $raw_name );
	if ( '' === $name ) {
		continue;
	}
	// Consolidated governments ("Nashville-Davidson") and "Urban Honolulu" display by their common name.
	$entry = array( $state, $aliases ? $aliases[0] : $name, round( (float) $row[ $col['INTPTLAT'] ], 4 ), round( (float) $row[ $col['INTPTLONG'] ], 4 ), $pop );
	foreach ( array_merge( array( $name ), $aliases ) as $label ) {
		$places[ lnkup_build_key( $label ) ][] = $entry;
	}
	$kept++;
}
fclose( $gaz_handle );

foreach ( $places as $key => $list ) {
	usort(
		$list,
		static function ( $a, $b ) {
			return $b[4] <=> $a[4];
		}
	);
	$seen = array();
	$out  = array();
	foreach ( $list as $entry ) {
		if ( isset( $seen[ $entry[0] ] ) ) {
			continue;
		}
		$seen[ $entry[0] ] = true;
		$out[]             = $entry;
	}
	$places[ $key ] = $out;
}
ksort( $places );

$target = dirname( __DIR__ ) . '/includes/location/data/us-places.php';
$lines  = array();
foreach ( $places as $key => $list ) {
	$entries = array();
	foreach ( $list as $entry ) {
		$entries[] = sprintf( "['%s',%s,%s,%s,%d]", $entry[0], var_export( $entry[1], true ), $entry[2], $entry[3], $entry[4] );
	}
	$lines[] = var_export( (string) $key, true ) . '=>[' . implode( ',', $entries ) . ']';
}
$code = "<?php\n/**\n * Generated by scripts/build-us-places.php from US Census 2023 Gazetteer + 2023 population\n * estimates (public domain). Do not edit by hand.\n *\n * key => list of [state, name, lat, lng, population], most populous first.\n *\n * @package LNKup_Marketplace\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn [\n" . implode( ",\n", $lines ) . "\n];\n";
file_put_contents( $target, $code );
fwrite( STDOUT, sprintf( "Wrote %d places under %d keys to %s\n", $kept, count( $places ), $target ) );
